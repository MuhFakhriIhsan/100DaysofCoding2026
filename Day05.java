public class Main {
	public static void main(String[] args) {
	
		//float adalah tipe data pecahan dengan presisi tunggal dan penulisannya didalam kode harus diakhiri huruf (f).
		
		//double adalah tipe data pecahan dengan presisi ganda dan tanpa menggunakan akhiran huruf.
			
		float beratbadan = 50.9f;
		double tinggibadan = 168.81;
		
		System.out.println("Berat badan saya : " + beratbadan + " kg");
		System.out.println("Tinggi badan saya : " + tinggibadan + " cm");
	}
}
